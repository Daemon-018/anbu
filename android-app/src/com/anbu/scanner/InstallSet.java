package com.anbu.scanner;

import android.content.Context;
import android.database.Cursor;
import android.net.Uri;
import android.provider.OpenableColumns;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.List;
import java.util.Locale;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Turns a file the user opened or shared into something the installer can use.
 *
 * <p>Everything is copied into ANBU's private cache first. A plain APK is used as-is;
 * an {@code .apks}, {@code .xapk} or other ZIP bundle is inspected, its split APKs are
 * extracted, and one of them is chosen as the primary (the base APK that carries the
 * package identity). Extracted names are generated by this class, never taken from the
 * archive, so a malicious ZIP cannot write outside the cache directory.</p>
 */
public final class InstallSet {

    /** Archive entry count and size limits keep a decompression bomb from filling the phone. */
    private static final int MAX_ENTRIES = 4000;
    private static final long MAX_ENTRY_BYTES = 2L * 1024 * 1024 * 1024;
    private static final long MAX_TOTAL_BYTES = 4L * 1024 * 1024 * 1024;
    private static final int BUFFER = 64 * 1024;

    private InstallSet() {
    }

    /** Everything the installer and the decision screen need about one selection. */
    public static final class Result {
        public final File dir;
        public final List<File> apks = new ArrayList<>();
        public File primary;
        public String displayName = "Selected file";
        public String sha256 = "";
        public long totalBytes;
        /** "apk", "apks", "xapk" or "bundle" — only used for wording. */
        public String kind = "apk";
        /** A non-fatal omission the user should know about (currently OBB files). */
        public String warning;
        /** Non-null when the selection cannot be installed at all. */
        public String error;

        Result(File dir) {
            this.dir = dir;
        }
    }

    /**
     * Copies and unpacks a selection. Safe to call from a background thread; no Android UI
     * is touched. Always check {@link Result#error} before using the APK list.
     */
    public static Result prepare(Context context, Uri uri) {
        File base = new File(context.getCacheDir(), "gatekeeper");
        if (!base.exists() && !base.mkdirs()) {
            Result failed = new Result(null);
            failed.error = "ANBU could not create a private working directory.";
            return failed;
        }
        prune(base);

        Result result = new Result(new File(base, "job-" + System.nanoTime()));
        if (!result.dir.mkdirs()) {
            result.error = "ANBU could not create a private working directory.";
            return result;
        }

        String name = displayName(context, uri);
        result.displayName = name;
        String lower = name.toLowerCase(Locale.US);
        if (lower.endsWith(".apks")) {
            result.kind = "apks";
        } else if (lower.endsWith(".xapk") || lower.endsWith(".apkm")) {
            result.kind = "xapk";
        }

        File copy = new File(result.dir, "selection");
        try {
            copyUri(context, uri, copy);
        } catch (Exception e) {
            result.error = "The selected file could not be read: " + reason(e);
            cleanup(result);
            return result;
        }
        if (copy.length() == 0) {
            result.error = "The selected file is empty.";
            cleanup(result);
            return result;
        }

        try {
            unpack(copy, result);
        } catch (Exception e) {
            result.error = "The selected file is not a usable Android package: " + reason(e);
            cleanup(result);
            return result;
        }
        if (result.error != null) {
            cleanup(result);
            return result;
        }

        result.totalBytes = 0;
        for (File apk : result.apks) result.totalBytes += apk.length();
        try {
            result.sha256 = sha256(result.primary);
        } catch (Exception ignored) {
            // Hashing is informational; a failed read is caught by the scan itself.
        }
        return result;
    }

    /** Removes the whole working directory; safe to call more than once. */
    public static void cleanup(Result result) {
        if (result != null && result.dir != null) delete(result.dir);
    }

    // ------------------------------------------------------------------- unpack

    private static void unpack(File copy, Result result) throws IOException {
        ZipFile zip;
        try {
            zip = new ZipFile(copy);
        } catch (IOException e) {
            throw new IOException("it is not a ZIP/APK archive");
        }
        try {
            List<ZipEntry> entries = new ArrayList<>();
            Enumeration<? extends ZipEntry> all = zip.entries();
            while (all.hasMoreElements()) {
                if (entries.size() >= MAX_ENTRIES) {
                    throw new IOException("it contains too many files");
                }
                entries.add(all.nextElement());
            }
            if (entries.isEmpty()) throw new IOException("the archive is empty");

            boolean rootManifest = false;
            List<ZipEntry> rootApks = new ArrayList<>();
            List<ZipEntry> splitApks = new ArrayList<>();
            List<ZipEntry> standaloneApks = new ArrayList<>();
            int obb = 0;

            for (ZipEntry entry : entries) {
                String entryName = entry.getName();
                if (entryName == null) continue;
                String safe = entryName.replace('\\', '/');
                if (safe.startsWith("/") || safe.contains("../") || safe.contains(":/")) {
                    continue; // never trust an archive that tries to escape its own root
                }
                String entryLower = safe.toLowerCase(Locale.US);
                if (entry.isDirectory()) continue;

                if (safe.startsWith("Android/obb/") || safe.startsWith("android/obb/")) {
                    obb++;
                    continue;
                }
                if (!entryLower.endsWith(".apk")) {
                    if (!safe.contains("/") && safe.equals("AndroidManifest.xml")) {
                        rootManifest = true;
                    }
                    continue;
                }
                if (!safe.contains("/")) {
                    rootApks.add(entry);
                } else if (entryLower.startsWith("splits/")) {
                    splitApks.add(entry);
                } else if (entryLower.startsWith("standalones/")) {
                    standaloneApks.add(entry);
                }
            }

            if (rootManifest) {
                result.apks.add(copy);
                result.primary = copy;
                result.kind = "apk";
                return;
            }

            List<ZipEntry> chosen;
            if (!splitApks.isEmpty()) {
                chosen = splitApks;
                result.kind = result.kind.equals("apk") ? "bundle" : result.kind;
            } else if (!standaloneApks.isEmpty()) {
                chosen = new ArrayList<>();
                chosen.add(largest(standaloneApks));
                result.kind = result.kind.equals("apk") ? "bundle" : result.kind;
            } else if (!rootApks.isEmpty()) {
                chosen = rootApks;
                result.kind = result.kind.equals("apk") ? "bundle" : result.kind;
            } else {
                throw new IOException("no APK files were found inside it");
            }

            int index = 0;
            long total = 0;
            List<String> names = new ArrayList<>();
            for (ZipEntry entry : chosen) {
                long declared = entry.getSize();
                if (declared > MAX_ENTRY_BYTES) {
                    throw new IOException("an APK inside it is too large");
                }
                File out = new File(result.dir, "part-" + index + ".apk");
                index++;
                long written = extract(zip, entry, out, MAX_ENTRY_BYTES, MAX_TOTAL_BYTES - total);
                total += written;
                result.apks.add(out);
                names.add(entry.getName());
            }
            if (result.apks.isEmpty()) throw new IOException("no APK files could be extracted");

            // Keep the original entry names around long enough to find the base APK, then
            // move it to the front: PackageInstaller expects the base first.
            result.primary = choosePrimary(result.apks, names);
            result.apks.remove(result.primary);
            result.apks.add(0, result.primary);
            if (obb > 0) {
                result.warning = "This bundle also contains " + obb
                        + (obb == 1 ? " OBB expansion file" : " OBB expansion files")
                        + ". Android 11+ does not let ANBU write those to Android/obb, so they "
                        + "were not installed. If the app needs them, add them with a file "
                        + "manager that has All-files access, or the app may fail to start.";
            }
        } finally {
            try {
                zip.close();
            } catch (IOException ignored) {
            }
        }
    }

    private static ZipEntry largest(List<ZipEntry> entries) {
        ZipEntry best = entries.get(0);
        for (ZipEntry entry : entries) {
            if (entry.getSize() > best.getSize()) best = entry;
        }
        return best;
    }

    /**
     * The base APK carries the package identity and must be written first. Bundles from
     * bundletool name it {@code base-master.apk}; other tools use {@code base.apk} or put
     * "base" in the name. Falling back to the largest APK is better than guessing wrong.
     *
     * <p>{@code files} and {@code names} are parallel lists; the extracted files were
     * renamed to {@code part-N.apk}, so the original entry name is the only clue.</p>
     */
    private static File choosePrimary(List<File> files, List<String> names) {
        for (int i = 0; i < files.size(); i++) {
            String name = baseName(names.get(i));
            if (name.equalsIgnoreCase("base-master.apk") || name.equalsIgnoreCase("base.apk")) {
                return files.get(i);
            }
        }
        for (int i = 0; i < files.size(); i++) {
            String name = baseName(names.get(i)).toLowerCase(Locale.US);
            if (name.startsWith("base-") || name.startsWith("base_")) return files.get(i);
        }
        for (int i = 0; i < files.size(); i++) {
            if (baseName(names.get(i)).toLowerCase(Locale.US).contains("base")) {
                return files.get(i);
            }
        }
        // XAPK bundles often use the package id for the base and "config.*" for splits.
        for (int i = 0; i < files.size(); i++) {
            String name = baseName(names.get(i)).toLowerCase(Locale.US);
            if (!name.startsWith("config.") && !name.startsWith("split_config")) {
                return files.get(i);
            }
        }
        File best = files.get(0);
        for (File file : files) {
            if (file.length() > best.length()) best = file;
        }
        return best;
    }

    private static String baseName(String path) {
        if (path == null) return "";
        String safe = path.replace('\\', '/');
        int slash = safe.lastIndexOf('/');
        return slash >= 0 ? safe.substring(slash + 1) : safe;
    }

    // --------------------------------------------------------------------- io

    private static long extract(ZipFile zip, ZipEntry entry, File out,
                                long entryLimit, long totalLimit) throws IOException {
        if (totalLimit <= 0) throw new IOException("it expands to more than ANBU will unpack");
        InputStream in = null;
        FileOutputStream stream = null;
        long total = 0;
        try {
            in = zip.getInputStream(entry);
            stream = new FileOutputStream(out);
            byte[] buffer = new byte[BUFFER];
            int read;
            while ((read = in.read(buffer)) >= 0) {
                total += read;
                if (total > entryLimit || total > totalLimit) {
                    throw new IOException("an APK inside it expands to too much data");
                }
                stream.write(buffer, 0, read);
            }
            stream.flush();
            stream.getFD().sync();
            return total;
        } catch (IOException e) {
            delete(out);
            throw e;
        } finally {
            if (in != null) {
                try {
                    in.close();
                } catch (IOException ignored) {
                }
            }
            if (stream != null) {
                try {
                    stream.close();
                } catch (IOException ignored) {
                }
            }
        }
    }

    private static void copyUri(Context context, Uri uri, File out) throws IOException {
        InputStream in = context.getContentResolver().openInputStream(uri);
        if (in == null) throw new IOException("the provider returned no data");
        FileOutputStream stream = null;
        try {
            stream = new FileOutputStream(out);
            byte[] buffer = new byte[BUFFER];
            int read;
            long total = 0;
            while ((read = in.read(buffer)) >= 0) {
                total += read;
                // The raw container is copied, not expanded; this only stops absurd inputs.
                if (total > MAX_TOTAL_BYTES) {
                    throw new IOException("the file is larger than ANBU will copy");
                }
                stream.write(buffer, 0, read);
            }
            stream.flush();
            stream.getFD().sync();
        } finally {
            try {
                in.close();
            } catch (IOException ignored) {
            }
            if (stream != null) {
                try {
                    stream.close();
                } catch (IOException ignored) {
                }
            }
        }
    }

    private static String displayName(Context context, Uri uri) {
        String name = null;
        Cursor cursor = null;
        try {
            cursor = context.getContentResolver().query(uri,
                    new String[]{OpenableColumns.DISPLAY_NAME}, null, null, null);
            if (cursor != null && cursor.moveToFirst()) {
                int column = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME);
                if (column >= 0) name = cursor.getString(column);
            }
        } catch (RuntimeException ignored) {
            // Fall back to the URI's last segment below.
        } finally {
            if (cursor != null) {
                try {
                    cursor.close();
                } catch (RuntimeException ignored) {
                }
            }
        }
        if (name == null || name.trim().isEmpty()) {
            name = uri.getLastPathSegment();
        }
        if (name == null || name.trim().isEmpty()) name = "Selected file";
        int slash = Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\'));
        if (slash >= 0) name = name.substring(slash + 1);
        return name;
    }

    private static String sha256(File file) throws Exception {
        MessageDigest digest = MessageDigest.getInstance("SHA-256");
        InputStream in = new java.io.FileInputStream(file);
        try {
            byte[] buffer = new byte[BUFFER];
            int read;
            while ((read = in.read(buffer)) >= 0) digest.update(buffer, 0, read);
        } finally {
            try {
                in.close();
            } catch (IOException ignored) {
            }
        }
        StringBuilder hex = new StringBuilder(64);
        for (byte b : digest.digest()) {
            hex.append(Character.forDigit((b >> 4) & 0xF, 16));
            hex.append(Character.forDigit(b & 0xF, 16));
        }
        return hex.toString();
    }

    /**
     * Drops working directories left behind by a crash or a killed process. Six hours is
     * long enough that an install the user left open is not pulled out from under them.
     */
    private static void prune(File base) {
        File[] children = base.listFiles();
        if (children == null) return;
        long cutoff = System.currentTimeMillis() - 6L * 60 * 60 * 1000;
        for (File child : children) {
            if (child.lastModified() < cutoff) delete(child);
        }
    }

    /** Recursive delete; ignores failures because the cache is best-effort. */
    public static void delete(File file) {
        if (file == null) return;
        File[] children = file.listFiles();
        if (children != null) {
            for (File child : children) delete(child);
        }
        //noinspection ResultOfMethodCallIgnored
        file.delete();
    }

    private static String reason(Exception e) {
        String message = e.getMessage();
        if (message == null || message.trim().isEmpty()) return e.getClass().getSimpleName();
        return message;
    }
}
